#include <cstdio>   /* printf —— C++ 里也能用，比 cout 更好控制格式 */
#include <array>    /* std::array，第 4.10 节的主角 */

/* ---------- 段 3 用的函数：二维数组传参的标准写法 ---------- */
/* 形参 int (*p)[3] ：p 是一个指针，指向「含 3 个 int 的数组」。
 * 为什么不写 int p[][3]？两者等价，但这个写法能一眼看出「它是指针」，
 * 而且 IMPORTANT：不管写哪种，这里的 3 都不能省 —— 编译器要靠它算 p+1 跨多少字节。 */
void print_mat(int (*p)[3], int rows)
{
    /* ★ 这里 sizeof(p) 必然是 8 —— 传进函数的永远是地址，不是整个数组。
     * 这就是「数组退化」：长度信息在函数里拿不回来，所以必须额外传一个 rows。 */
    printf("  函数里 sizeof(p) = %zu  <- 退化成指针，长度丢了，所以要额外传 rows=%d\n",
           sizeof p, rows);
    for (int i = 0; i < rows; i++)
        printf("    p[%d] = %d %d %d\n", i, p[i][0], p[i][1], p[i][2]);
}

int main(void)
{
    /* ===== 段 1：int *pa[3]  vs  int (*pb)[3] ===== */
    int a[3] = {10, 20, 30};
    int b[3] = {40, 50, 60};

    int *pa[3];      /* 读法：pa 往右是 [3] → pa 是数组 → 往左 int* → 元素是指针 */
    pa[0] = a;       /* 所以它是一个「装着 3 个指针的数组」 */
    pa[1] = b;

    int (*pb)[3];    /* 读法：括号里 *pb → pb 是指针 → 出括号 [3] → 指向含 3 个 int 的数组 */
    pb = &a;         /* 所以它是一个「指向整个数组的指针」，赋值要用 &a 而不是 a */

    /* ★ 最快的试金石：sizeof。数组量的是「整个货架」，指针量的是「一张纸条」。 */
    printf("【段1】sizeof(pa) = %zu  <- 3 个指针 = 3x8\n", sizeof pa);   /* 24 */
    printf("       sizeof(pb) = %zu  <- 就 1 个指针\n", sizeof pb);       /* 8  */
    printf("       *pa[0] = %d, (*pb)[1] = %d\n", *pa[0], (*pb)[1]);      /* 10, 20 */

    /* ===== 段 2：pb + 1 跨整个数组 ===== */
    /* pa+1 跨 8 字节（下一个指针）；pb+1 跨 12 字节（跳过整个 int[3]）。
     * 同样写 +1，跨度差一倍多 —— 这就是「它指向的东西不一样大」。 */
    printf("【段2】pa+1 跨 %td 字节, pb+1 跨 %td 字节\n",
           (char *)(pa + 1) - (char *)pa,      /* 8  */
           (char *)(pb + 1) - (char *)pb);     /* 12 */

    /* ===== 段 3：二维数组传参（第 7 章 §7.3 的预演） ===== */
    int mat[2][3] = {{1, 2, 3}, {4, 5, 6}};
    printf("【段3】主函数里 sizeof(mat) = %zu  <- 2x3x4 = 24，长度还在\n", sizeof mat);
    print_mat(mat, 2);   /* 数组名 mat 退化成 &mat[0]，类型正好是 int(*)[3] */

    /* ===== 段 4：字符串表 = 二级指针（昨天那行 const antarctica_years **ppa 的真身） ===== */
    /* cmd 是「数组，元素是 const char*」；数组名一用就退化成「指向那个指针的指针」。
     * 所以二级指针不是谁发明出来折磨人的，它就是「指针数组」逼出来的。 */
    const char *cmd[] = {"start", "stop"};
    const char **ppc = cmd;              /* 两个 * = 两层间接 */
    printf("【段4】*ppc = %s, *(ppc+1) = %s\n", *ppc, *(ppc + 1));   /* start, stop */

    /* ===== 段 5：std::array —— 原生数组做不到的两件事（4.10 收尾） ===== */
    std::array<int, 3> x = {7, 8, 9};
    std::array<int, 3> y;
    y = x;                               /* ① 整体赋值。原生数组 int z[3]; z = x; 编译不过 */
    printf("【段5】y[0] = %d, y.size() = %zu  <- ② 它知道自己的长度\n", y[0], y.size());

    return 0;
}

/* ============ 你会问 ============
 * | 你会问                     | 答案 |
 * |---------------------------|------|
 * | %zu 是什么                | 打印 sizeof 的结果（类型 size_t）。用 %d 是未定义行为，可能打错数 |
 * | %td 是什么                | 打印两个指针相减的结果（类型 ptrdiff_t），同样不能用 %d |
 * | (char*) 为什么要强转      | 指针相减得到的是「元素个数」不是字节数；转成 char*（1 字节）后差值才等于字节数 |
 * | 段 2 的 pb+1 合法吗       | 合法但别解引用 —— pb 只指向 a 这一个数组，pb+1 是"墙外"，解引用是越界（ASan 会抓） |
 * | std::array 比原生数组慢吗 | 不慢，编译期定长，零额外开销。主线 B 的 C 语言里没有它，但 C++ 写代码时优先用它 |
 *
 * ============ 学习强度 ============
 * 背     ：sizeof 是区分「数组」和「指针」最快的试金石；二维数组传参必须带列数
 * 手打   ：int (*p)[3] 这种写法（写一次，知道括号是干嘛的）
 * 不背   ：%zu / %td 这些格式符，用到再看
 */
