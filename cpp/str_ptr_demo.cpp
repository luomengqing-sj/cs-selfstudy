/* ============================================================
   str_ptr_demo.cpp —— char* 与字符串字面量：每个量到底是什么
   注释即讲义（读代码 = 读讲解）

   编译：g++ -std=c++17 -g str_ptr_demo.cpp -o str_ptr && ./str_ptr
   ============================================================ */

#include <iostream>   // cout 在这里
#include <cstring>    // strlen 在这里（C 的 string.h 换成 C++ 的 cstring）
using namespace std;  // 省得每个都写 std::cout

int main()
{
    /* ---------- 第 0 步：这一行到底干了什么 ----------
       const char *bird = "wren";

       内存里发生两件事：
         1) 编译器把 'w','r','e','n','\0' 这 5 个字节放进「只读数据段 .rodata」
            （跟全局变量放一起，程序一启动就在，程序运行期间一直活着）
         2) 把这块内存的「首地址」赋给 bird

       ⚠️ 书上写 char *bird = "wren";（没有 const）
          那是 C++98 的老写法，现代 g++ 会警告：
          "ISO C++ forbids converting a string constant to 'char*'"
          因为字面量是只读的，用可写的 char* 去接是撒谎。
          正确写法就是这里的 const char *bird。
    */
    const char *bird = "wren";

    /* ---------- 内存全景图（把这张图记住，下面 8 行就全通了）----------

       只读段 .rodata（程序加载时就存在，写它 = 段错误）
         0x4000 : 'w'     ← bird 存的就是这个地址
         0x4001 : 'r'
         0x4002 : 'e'
         0x4003 : 'n'
         0x4004 : '\0'    ← 结束符。它不显示，但它是"打印到哪停"的唯一依据

       栈（局部变量所在）
         bird : [ 0x4000 ]   ← 指针变量自己占 8 字节，里面存的是上面那个地址
    */

    /* ---------- 1. bird 本身 ---------- */
    cout << "1  bird            : " << bird << '\n';
    // 输出：wren
    // 为什么不是地址？因为 cout 的 << 对 char* 有一条「专属重载」：
    //     ostream& operator<<(ostream&, const char*)   ← 专门给字符串准备的
    // 它做的事是：从这个地址开始，一个字符一个字符往外打，
    //            一直打到遇见 '\0' 才停。
    // 这是 C++ 里唯一一个「你给它地址，它偏不给你打地址」的地方。

    /* ---------- 2. 想看地址：转成 void* ---------- */
    cout << "2  (void*)bird     : " << (void*)bird << '\n';
    // 输出：0x4008a4 之类的十六进制地址
    // (void*) = "别管它指向什么类型了，就当它是个光秃秃的地址"
    // 类型一变成 void*，上面那条专属重载就不匹配了，
    // 于是落到普通指针那条：
    //     ostream& operator<<(ostream&, const void*)   ← 打印地址
    // ★ 口诀：char* 会自动解开；要看地址先转 void*

    /* ---------- 3. *bird：解引用，拿到第一个字符 ---------- */
    cout << "3  *bird           : " << *bird << '\n';
    // 输出：w
    // *bird == bird[0]，都是「bird 指向的那个字符」

    /* ---------- 4. bird + 1：地址跨 1 字节（因为 char 就是 1 字节）---------- */
    cout << "4  bird + 1        : " << bird + 1 << '\n';
    // 输出：ren
    // 它还是 const char*，所以照样走专属重载 → 还是打内容，不是地址！
    // 从 0x4001 开始打到 '\0' → "ren"
    // 步长 = sizeof(char) = 1，所以地址只 +1（对比：int* 是 +4）

    /* ---------- 5. 看了内容也看地址 ---------- */
    cout << "5  (void*)(bird+1) : " << (void*)(bird + 1) << '\n';
    // 输出：前一个地址 + 1（比如 0x4008a5）
    // 用来验证第 4 行：步长确实是 1 字节

    /* ---------- 6. &bird：指针变量「自己」的地址 ---------- */
    cout << "6  &bird           : " << &bird << '\n';
    // 输出：0x7ffd... 这种长地址（跟上面的 0x400... 明显不是一个段）
    // 三个东西别混：
    //    bird  = 它存的地址（0x4000，指向 'w'）
    //   *bird  = 它指向的值（'w'）
    //   &bird  = 指针变量自己在内存里的位置（0x7ffd...，栈上）
    // 类型是 const char**（指向指针的指针），没有专属重载 → 打地址

    /* ---------- 7. sizeof：量的是「盒子」不是「绳子」 ---------- */
    cout << "7  sizeof(bird)    : " << sizeof(bird) << '\n';
    // 输出：8（64 位机器上任何指针都是 8 字节）
    // ★ 不是 5！bird 只是一根指向绳子的手指头，绳子多长它不知道
    // 想知道字符串多长用 strlen（见下一行）

    /* ---------- 8. strlen：顺着绳子数到 '\0' ---------- */
    cout << "8  strlen(bird)    : " << strlen(bird) << '\n';
    // 输出：4
    // 不含 '\0'。sizeof 量盒子，strlen 量内容，两个数经常不一样

    /* ---------- 9. 对照组：数组版 ----------
       char nest[] = "wren";
       这行和上面那行长得像，干的活完全不同：
         - bird：栈上只有 8 字节的指针，真正的字符在只读段（不可改）
         - nest：栈上真的躺了 5 个字节的副本 w/r/e/n/\0（可改）
    */
    char nest[] = "wren";                      // 数组版：在栈上拷一份
    cout << "9  sizeof(nest)    : " << sizeof(nest) << '\n';
    // 输出：5 ← 关键差别！sizeof(数组名) 量的是整块数组，不是指针
    // 这也是昨天 4.8.2 卡住的那个点：数组名 ≠ 指针，sizeof 一眼就能区分

    // nest[0] = 'W';   // ✅ 合法：栈上的副本可以改
    // bird[0] = 'W';   // ❌ 段错误：写只读段。而且这行有 const，编译期就被拦

    /* ---------- 10. 谁能让谁改指向 ---------- */
    // nest = bird;   // ❌ 编译报错：数组名是常量地址，不能被赋值（不能站到别处）
    const char *other = "sparrow";
    bird = other;                              // ✅ 指针是变量，可以改指向
    cout << "10 bird 改指后     : " << bird << '\n';
    // 输出：sparrow
    // ★ 数组名是「钉死的门牌」，指针是「可以换的钥匙」

    return 0;
}
