/* ptr_demo.cpp —— 《C++ Primer Plus》第 4 章 §4.7–4.8（指针 / 自由存储空间 / 指针算术）动手配套
 *
 * 编译（普通）： g++ -std=c++17 -g ptr_demo.cpp -o ptr      && ./ptr
 * 编译（体检）： g++ -std=c++17 -g -fsanitize=address,undefined ptr_demo.cpp -o ptr_asan && ./ptr_asan
 *
 * 预期：
 *   普通版 —— 打印 7 段，第 6 段的值可能是垃圾数（看着"正常"，其实已经错了）
 *   ASan 版 —— 在第 6 段当场报红字 heap-use-after-free，并指出行号
 *
 * 读法：先自己看书 §4.7–4.8，再回来跑这个文件。跑完回答文末 3 个自检题。
 */
#include <cstdio>
#include <cstdint>

int main(void)
{
    /* ---------- 1. 数组名 = 首元素的地址 ----------
     * 类比：数组是一排信箱，数组名 a 就是「1 号信箱的位置」，不是「整排信箱」。
     * 所以 a[i] 和 *(a+i) 完全等价 —— 下标其实是"从 1 号信箱往后数 i 格，再打开"的简写。
     * 为什么书上强调这点：把数组传给函数时，传进去的就是这个地址，函数里 sizeof(a) 会变成指针大小（丢长度）。
     */
    int a[3] = {10, 20, 30};
    printf("1) a=%p  &a[0]=%p   是同一个地址吗：%s\n",
           (void *)a, (void *)&a[0], (a == &a[0]) ? "是" : "不是");
    printf("   a[1]=%d   *(a+1)=%d   <-- 两种写法，一个意思\n", a[1], *(a + 1));

    /* ---------- 2. 指针 +1 走多远？走 sizeof(所指向的类型) ----------
     * 类比：p+1 不是"地址加 1"，是"往后走一个格子的宽度"。int 一格 4 字节，char 一格 1 字节。
     * 这是指针算术最容易错的地方，也是将来读寄存器地址表时必须清醒的地方。
     */
    int  *pi = a;
    char  c[3] = {'A', 'B', 'C'};
    char *pc = c;
    printf("2) int  * : p=%p  p+1=%p  差 %ld 字节\n",
           (void *)pi, (void *)(pi + 1), (long)((char *)(pi + 1) - (char *)pi));
    printf("   char * : p=%p  p+1=%p  差 %ld 字节\n",
           (void *)pc, (void *)(pc + 1), (long)((char *)(pc + 1) - (char *)pc));

    /* ---------- 3. 一行声明两个变量时的经典坑 ----------
     * int* x, y;  里的 * 只属于 x，y 是普通的 int。
     * 为什么：* 是"贴在变量上的标记"，不是"贴类型上的"。写成 int *x, y; 就不容易误读。
     * 打印 sizeof 来证明：x 是指针（64 位机 8 字节），y 是 int（4 字节）。
     */
    int *x, y;              /* x 是 int*，y 是 int —— 不是两个指针 */
    printf("3) sizeof(x)=%zu(指针)   sizeof(y)=%zu(int)   <-- y 不是指针\n",
           sizeof(x), sizeof(y));
    (void)x; (void)y;       /* 这两行只是为了避免编译器警告"未使用" */

    /* ---------- 4. new / delete 必须成对 ----------
     * 类比：new 是向仓库（堆）租一格，delete 是退租。忘了退 = 内存泄漏（程序跑一天内存吃满）。
     * delete 完立刻把指针置 nullptr（C++11；C 里写 NULL）——
     * 否则它变成"悬空指针"：地址还在，但那块地已经不是你的了。
     */
    int *q = new int(42);   /* new int(42)：租一格 int，里面写 42 */
    printf("4) *q=%d\n", *q);
    delete q;
    q = nullptr;            /* 删完置空。对 nullptr 再 delete 是安全的（空操作） */

    /* ---------- 5. 数组用 new[]，就得用 delete[] ----------
     * 坑：new[] 配 delete（漏了方括号）是未定义行为 —— 通常只释放了第一格，其余泄漏。
     * 口诀：方括号要成对出现。
     */
    int *arr = new int[4]{1, 2, 3, 4};
    printf("5) arr[2]=%d\n", arr[2]);
    delete[] arr;

    /* ---------- 6. 释放后再用（use-after-free）----------
     * 这一行是故意写错的。普通编译时它可能"看起来没事"（打印出 7 或垃圾数），
     * 但那是假象 —— 那块地已经归还仓库，随时可能被别人写进去。
     * 用 ASan 版本跑，它会在这里打印红色报错 heap-use-after-free 并给出行号。
     * 这就是 -fsanitize 的价值：把"看起来没事"的错变成"当场抓住"。
     */
    int *d = new int(7);
    delete d;
    printf("6) 释放后再读 *d = %d   <-- 未定义行为，ASan 版会在这里报红字\n", *d);

    /* ---------- 7. 这一步是给你接嵌入式的 ----------
     * 芯片的寄存器 = 一个地址写死的内存格子。C 里操作寄存器，本质就是"对一个固定地址解引用"：
     *     #define GPIOA_ODR  (*(volatile uint32_t *)0x40020014)
     * 拆开读： (volatile uint32_t *)0x40020014  = 把这个数字当成地址，且它是 volatile 的
     *         最左边那个 *                      = 取这个地址里的内容
     * 所以 *reg |= (1u << 3); 就是 09-19 练过的"只置第 3 位"——指针和位运算在这里合流。
     */
    uint32_t  fake_reg = 0;        /* 假装这是某个 32 位寄存器 */
    uint32_t *reg = &fake_reg;     /* 拿到它的地址 */
    *reg |= (1u << 3);             /* 只把第 3 位置 1，其余位不动 */
    printf("7) fake_reg = 0x%08X   <-- 只有第 3 位亮起来\n", fake_reg);

    return 0;
}

/* ===================== 自检 3 题（跑完再答，别看书） =====================
 * 1. int a[3]; 在函数里 sizeof(a) 是 12，传给函数后 sizeof(a) 变成多少？为什么？
 *    答：8（64 位机）。传进去的是首元素地址（指针），长度信息丢了 —— 所以函数还要另收一个 len 参数。
 *
 * 2. int *p; p+1 地址加了几？
 *    答：4（sizeof(int)）。不是加 1。这是指针算术的头号误区。
 *
 * 3. delete 之后，那个指针变量本身的值变了吗？
 *    答：没变。它还存着旧地址，只是那块地已经不是你的了（悬空指针）。所以要手动 q = nullptr。
 *
 * 口诀：数组名即首址；+1 走一格宽；new/delete 成对，[] 也成对；删完置空防悬空。
 */
