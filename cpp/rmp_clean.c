/* ============================================================
 * rmp_clean.c —— 四电机转速统计（干净可编译版）
 *
 * 编译：gcc -std=c11 -Wall -g rmp_clean.c -o rmp
 * 运行：./rmp < data.txt
 *
 * ------------------------------------------------------------
 * 这一版专门标注了你那份 rmp.c 里踩的坑，照着注释对一遍：
 *
 *  坑1 形参的第二维必须是常量 MOTOR，不能是运行时读进来的 n
 *      int (*rmp)[MOTOR]  ✅      int (*rmp)[n]  ❌
 *      原因：编译器要靠它算步长（每行 16 字节），n 运行时才有
 *
 *  坑2 调用时【只写变量名】，不要再写一遍类型
 *      sum_a(rmp, n)              ✅
 *      sum_a(int(*rmp)[n])        ❌ 在 C++ 里这是强制转换 int(...)
 *
 *  坑3 是 printf，不是 print
 *
 *  坑4 参数之间用【逗号 ,】，不是【点 .】
 *      int ave_a(int (*rmp)[MOTOR], int n, int i)   ✅
 *      int ave_a(int (*rmp)[MOTOR], int n. int i)   ❌
 *
 *  坑5 两层循环各要一个循环变量，只写 i 会导致 'j' undeclared
 *
 *  坑6 括号要配对：printf("%d ", ave_a(rmp, n, j));
 *                                              ^  ^ ^
 *                                     内层右括号  外层右括号 + 分号
 *
 *  坑7 千万别把终端的报错输出粘贴进源文件 —— 会产生一堆 stray '\342'
 *      （\342 是 UTF-8 里 GCC 用的弯引号 ‘ U+2018 的第一个字节）
 * ============================================================ */

#include <stdio.h>              /* printf / scanf 都在这里 */

#define MOTOR 4                 /* 电机数：必须是编译期常量 */
#define MAXN  100               /* 最多采样次数 */

/* ---- 函数原型：只写类型，必须和下面的定义一字不差 ---- */
int sum_a(int (*rmp)[MOTOR], int n);           /* 全部转速总和 */
int ave_a(int (*rmp)[MOTOR], int n, int j);    /* 第 j 号电机的平均值 */
int max_a(int (*rmp)[MOTOR], int n);           /* 绝对值最大的电机号 */

int main(void)
{
    int n;                      /* 采样次数，从输入读进来 */
    int rmp[MAXN][MOTOR];       /* 第一维 = 第几次采样，第二维 = 电机号 */

    scanf("%d", &n);            /* 读 int 必须加 & */

    /* 坑5：i 管行（第几次采样），j 管列（几号电机），两个都要声明 */
    for (int i = 0; i < n; i++)
        for (int j = 0; j < MOTOR; j++)
            scanf("%d", &rmp[i][j]);

    /* 坑2：调用只写变量名 */
    printf("%d\n", sum_a(rmp, n));

    /* 坑6：ave_a(...) 自带一对括号，printf(...) 外面还要一对 */
    for (int j = 0; j < MOTOR; j++)
        printf("%d ", ave_a(rmp, n, j));

    /* 坑3：printf，不是 print */
    printf("\n%d\n", max_a(rmp, n));

    return 0;
}

/* 总和：把所有行、所有列扫一遍 */
int sum_a(int (*rmp)[MOTOR], int n)
{
    int s = 0;
    for (int i = 0; i < n; i++)
        for (int j = 0; j < MOTOR; j++)
            s += rmp[i][j];
    return s;
}

/* 第 j 号电机的平均值：固定列 j，扫所有行 */
int ave_a(int (*rmp)[MOTOR], int n, int j)
{
    int s = 0;
    for (int i = 0; i < n; i++)
        s += rmp[i][j];
    return s / n;               /* 整数除法，直接截断（题目要求） */
}

/* 绝对值最大的电机号；并列时取编号小的 */
int max_a(int (*rmp)[MOTOR], int n)
{
    int best  = 0;              /* 冠军电机号 */
    int bestv = -1;             /* 冠军的绝对值。初值 -1 保证第一个必被选中 */
    for (int j = 0; j < MOTOR; j++) {
        for (int i = 0; i < n; i++) {
            int v = rmp[i][j];
            if (v < 0) v = -v;          /* 取绝对值 */
            if (v > bestv) {            /* 严格大于 → 并列时保留编号小的 j */
                bestv = v;
                best  = j;
            }
        }
    }
    return best;
}

/* ============================================================
 * 你会问
 * ------------------------------------------------------------
 * Q: 为什么不能写 int a[][4]？
 * A: 能写，int a[][4] 和 int (*a)[4] 在形参里完全等价。
 *    我用指针写法是为了让你记住：它本质是个指针，+1 跨 16 字节。
 *
 * Q: 第二维为什么不能是变量 n？
 * A: 编译器要靠它算步长。C99 的变长数组(VLA)允许，但你现在用 gcc 默认
 *    标准下没问题；真正的底线是这个值必须在【编译期】可知。
 *
 * Q: rmp 传给函数时是什么类型？
 * A: int[100][4] 的数组名退化成 int (*)[4]，正好对上形参。
 *    第一维（行数）在这时候丢了，所以必须额外把 n 传进去。
 *
 * Q: 我能不能用 int **rmp？
 * A: 不能。二维数组在内存里是连续的一整块，中间没有"指针数组"那一层。
 *    int** 的 +1 跨 8 字节，会直接错位读到垃圾。
 *
 * Q: stray '\342' 以后怎么一眼认出来？
 * A: 见到 stray '\xxx' = 文件里有非 ASCII 字符。99% 是两种原因：
 *    中文输入法（全角括号/分号），或者把终端输出粘进了源文件。
 *
 * 学习强度
 *   - 调用处只写变量名、不再写类型      → 背
 *   - 形参第二维必须是常量              → 背
 *   - printf / 逗号 / 括号配对          → 背（手滑，但每次都浪费十分钟）
 *   - 编译报错是给你看的，不是给你抄的  → 背（这条最重要）
 * ============================================================ */
