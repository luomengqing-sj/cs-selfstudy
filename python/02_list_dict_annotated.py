# ------------------------------------------------------------
# 【开场 · Python 和 C++ 最根本的一处区别】
# C++   ：变量是「盒子」。int nums[4]; 先造盒子，类型焊死在盒子上，一辈子是 int
# Python：变量是「标签」。nums = [5,2,9,1] 是把一张叫 nums 的便签贴在那一坨数据上
#         便签能撕下来贴到别处，所以下面再写 nums = "abc" 也合法（C++ 里绝对不行）
#         这就是「静态类型」和「动态类型」的分界线
# ------------------------------------------------------------

nums = [5, 2, 9, 1]
#      ^^^^^^^^^^^ 列表字面量 ≈ C++ 的 vector<int> nums = {5, 2, 9, 1};
#  ★ list 可以混装不同类型：[1, "a", 3.5] 也不报错
#    （C++ 的 vector 必须同类型 —— 如果你习惯的是 vector<int>，这里要扭一下）

nums.append(7)
#    ^^^^^^ 「追加一个元素到末尾」= C++ 的 nums.push_back(7)
#  ★★★ 头号坑：append 是【原地修改】，返回值是 None
#      x = nums.append(8)  →  x 是 None，不是新列表！
#      push_back 返回 void，你不会写 auto x = v.push_back(8)；
#      Python 里这么写【不报错】，所以更阴 —— 错误会延迟到用到 x 的地方才炸
#  ★ 一次加多个：nums.extend([8, 9]) 或 nums += [8, 9]
#    append 只吃「一个东西」：nums.append([8,9]) 会把整个列表当【一个元素】塞进去
#    → 长度从 5 变成 6，第 6 个元素是个列表 [8,9]。要的是 extend

nums.sort()
#    ^^^^ 原地排序 = C++ 的 sort(nums.begin(), nums.end())
#  ★ 同样【返回 None】。想要「排好序的新列表、原列表不动」→ 写 sorted(nums)
#    C++ 对照：sort() 返回 void，想保留原序列得先 vector<int> b = a; sort(b.begin(), b.end());
#             Python 里 sorted(nums) 一行干完这两件事
#  记忆法：带 -ed 的（sorted）返回结果，不带 -ed 的（sort）原地改。
#          同理还有 reverse（原地） / reversed（返回迭代器）

print(nums)             # [1, 2, 5, 7, 9]
#  ★ 到这儿 nums 已经被前面两次【原地改】排好序了。Python 的操作大部分是原地改，
#    C++ 的函数你还能从参数上（`&` 引用）看出来，Python 只能靠记

print(nums[1:3])        # [2, 5]
#          ^ ^ 冒号左边=起点下标，右边=终点下标，【左闭右开】：含 1，不含 3
#  ★ C++ 干这事要写：vector<int> sub(nums.begin()+1, nums.begin()+3);
#  ★ 为什么非要左闭右开？因为这样【元素个数 = 终点 - 起点】，3-1=2 个，不用纠结 ±1
#    同一个规则 C++ 里你早见过：sort(v.begin(), v.end()) 的 end() 是「尾后」，
#    指向最后一个元素的【后面】，不是最后一个元素
#  ★ 省略写法（这四个记牢，用一辈子）：
#      nums[:3]  从头到下标 2        nums[2:]   从下标 2 到末尾
#      nums[:]   整个列表的【副本】   nums[::2]  从头到尾隔一个取一个
#  ★ nums[:] 常被用来「复制列表」。因为 Python 里写 b = nums 只是多贴一张便签，
#    两块便签指着同一坨数据 —— 改 b 会动到 nums！想要真副本必须 nums[:] 或 nums.copy()

print(nums[-1])         # 9
#          ^^ 负数下标 = 从后往前数。-1 = 最后一个，-2 = 倒数第二个
#  ★ C++ 里 nums[-1] 是未定义行为（UB）：没人拦你，跑到天涯海角才崩，最难查
#    Python 内部把它翻译成 nums[len(nums) + (-1)] = nums[4] = 9
#  三个最常用：-1 最后一个 / nums[:n] 前 n 个 / nums[-n:] 后 n 个

# ------------------------------------------------------------
# 【列表推导】Python 最招牌的语法。先看懂它【等价于什么】，再看简洁写法
# ------------------------------------------------------------
squares = [n * n for n in nums]
#         ^                     ^  外层方括号 = 「我要造一个新列表」
#                  ^^^^^^^^^^^ for 部分：从哪来（每轮把 nums 的元素绑到 n 上）
#           ^^^^^ 最前面：每轮要【塞进去的那个值】
#
#  ★ 读法口诀：先看后面的 for 知道「从哪来」，再看前面的表达式知道「变成什么样」
#
#  C++ 要写四行（对比一下，这就是 S0 的验收材料）：
#      vector<int> squares;
#      for (int n : nums)
#          squares.push_back(n * n);
#
#  等价展开（觉得绕就先在脑子里展开成这样）：
#      squares = []
#      for n in nums:
#          squares.append(n * n)
#
#  ★ 别手滑写成圆括号 (n*n for n in nums) —— 那是【生成器】，不是列表，
#    print 出来会是 <generator object ...> 这种东西，不是你要的数字

even = [n for n in nums if n % 2 == 0]
#       ^ 表达式部分可以直接就是 n —— 「原样塞进去」
#                       ^^^^^^^^^^^^^^ 末尾加 if = 过滤器，不满足就跳过，不塞
#  C++ 对照：for (int n : nums) if (n % 2 == 0) even.push_back(n);
print(squares)          # [1, 4, 25, 49, 81]
print(even)             # [2]

# ------------------------------------------------------------
# 【dict 字典】≈ C++ 的 unordered_map（哈希表）
# ------------------------------------------------------------
count = {}
#        ^^ 空花括号 = 空字典。别混：空列表 []、空字典 {}、空集合 set()
#           （空集合没有字面量写法，因为 {} 被字典占了）

for ch in "hello":
    #   ^^ 直接遍历字符串，每轮拿一个【字符】= C++ 的 for (char ch : string("hello"))
    #      Python 没有单独的 char 类型，一个字符就是长度为 1 的字符串 'h'
    #      （注意：Python 里单引号和双引号【完全等价】，'h' 和 "h" 是一个东西）

    count[ch] = count.get(ch, 0) + 1
    #    ^^^ 用方括号取值/赋值，写得跟 C++ 的 map[key] 一模一样 ——
    #        【但行为差很大，这是从 C++ 过来最容易翻车的地方】：
    #
    #        Python : dict[key] 取不到 → 当场抛 KeyError，程序崩
    #        C++    : map[key] 取不到 → 自动插入一个默认值（int 就是 0），不崩
    #
    #        ^^^^^^^^ get(k, d)：取 k 的值，【取不到就返回 d】，既不崩也不插入
    #                 count.get(ch, 0) 读出来就是一句人话：
    #                 「这个字母现在是几次？之前没出现过就当它是 0 次」
    #
    #        整句 = 「把 ch 的计数加 1，没有就从 0 开始算」
    #
    #  C++ 等价写法（顺便看看两边差几行）：
    #      unordered_map<char, int> count;
    #      for (char ch : string("hello"))
    #          count[ch]++;      // C++ 因为会自动补 0，一行搞定
    #  Python 必须多念一次 .get(k, 0)，因为它的 [] 不会替你兜底 ——
    #  这就是那句 .get(k, 0) 的【全部由来】，不是什么高级写法，是被逼的

print(count)            # {'h': 1, 'e': 1, 'l': 2, 'o': 1}
#  ★ Python 3.7 起 dict 保持插入顺序，所以稳定是 h/e/l/o 这个顺序
#    unordered_map 是无序的 —— 两边最容易在不经意间造成差异的地方

# ============================================================
# 【C++ ↔ Python 速查】（不用背，忘了回来查这一张表）
# ============================================================
# vector<int> v = {1,2,3}   →  v = [1, 2, 3]
# v.push_back(x)            →  v.append(x)              （都返回空）
# sort(v.begin(), v.end())  →  v.sort()                （都返回空）
# —                         →  sorted(v)               （返回新列表，C++ 没有单行等价物）
# v[i]                      →  v[i]                    （Python 支持负数，C++ 是 UB）
# v.size()                  →  len(v)                  （注意是 len(v) 不是 v.len()）
# —                         →  v[i:j]                  （切片，C++ 要用迭代器构造）
# unordered_map<K,V> m      →  m = {}
# m[k]（自动补 0）          →  m.get(k, 0)             （Python 的 m[k] 取不到会崩）
# range-for + push_back     →  [f(x) for x in xs]      （列表推导）
