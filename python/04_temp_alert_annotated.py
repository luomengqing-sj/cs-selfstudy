# -*- coding: utf-8 -*-
"""
P0002 电机温度告警 —— 注释即讲义版（对照 04_temp_alert.py，原文件不动）

题目要求：找出温度严格大于 T 的电机编号，按温度从高到低输出；
          温度相同按编号从小到大；没有就输出 -1。
"""

# ---------- 第 1 步：读输入 ----------
# input() 读走一整行（字符串）-> split() 按空格切开 -> map(int,...) 逐个转成整数
# 左边写两个名字，Python 会把右边的结果"拆包"分别赋值（这叫序列解包）
n, T = map(int, input().split())

# 第二行是 n 个温度，list(...) 把它们收成一个列表
temp = list(map(int, input().split()))

# ---------- 第 2 步：筛出超温电机的"编号" ----------
# 关键认知：绝对不能去 sort(temp)！一排温度，编号就跟温度脱钩了，
# 再也说不清 92 度是哪个电机。所以只能新建一个"编号列表"来排。
idx = [i for i in range(n) if temp[i] > T]
#     │   └──────┬──────┘  └───────┬───────┘
#     │          │                 │
#     │          │                 └─ 筛选条件：只有满足的才收
#     │          └─ 遍历 0..n-1
#     └─ 放进列表的东西 = 编号 i（不是温度！写 temp[i] 就把编号丢了）
#
# 这叫"列表推导式"，读法："把满足 temp[i] > T 的那些 i，收集成一个列表"
# C++ 里对应 copy_if + back_inserter，但 Python 一行搞定。
#
# 等价的笨写法（看不懂推导式就先写这个，能跑再改）：
#   idx = []
#   for i in range(n):
#       if temp[i] > T:
#           idx.append(i)

# ---------- 第 3 步：给编号排序 ----------
# 注意：排的是 idx（编号列表），但排序依据要去 temp 里查 —— 这就是 key 的作用
idx.sort(key=lambda x: (-temp[x], x))
#        └───┬───┘ └────────┬────────┘
#            │              │
#            │              └─ 排序依据：一个"元组"= 双关键字
#            │                 先按 -temp[x]（温度取负 = 降序）
#            │                 相同再按 x（编号升序）
#            └─ key 告诉 sort：用这个函数算出来的东西当排序依据
#                              而不是用元素本身
#
# C++ 对照：C++ 写 sort(v.begin(), v.end(), cmp) 传"比较函数"（两个参数）；
#           Python 反过来，你给一个"取出排序键"的函数（一个参数）。更短。
#
# ★ 进阶：其实 key=lambda x: -temp[x] 就够了！
#   因为 idx 是 [1,2,4] 这种天然升序生成的，而 Python 的 sort 是"稳定排序"
#   （相等的元素保持原有相对顺序），所以同温度时编号升序会自动成立。
#   显式写两个关键字更保险，不容易改错。

# ---------- 第 4 步：输出 ----------
if not idx:          # not idx = 列表是空的（空列表、0、空字符串都算"假"）
    print(-1)
else:
    print(*idx)      # ★ 这个 * 最关键：把列表"拆开"成一个个参数
                     #   print(*[2,4,1]) 等价于 print(2, 4, 1) -> 输出 "2 4 1"
                     #   不写 * 会输出 "[2, 4, 1]"（带中括号和逗号），格式直接错

# ---------- 复杂度 ----------
# 筛选 O(n)；排序 O(k log k)，k = 超温电机个数。
# 对比暴力做法（每次找最大值再删）O(k*n) —— n=1000 时差别明显。

# ---------- 三条易错点 ----------
# 1. 超温是"严格大于" > T，等于阈值不算。写成 >= 样例 #3 会多输出一个 0。
# 2. 没超温时输出单独的 -1，别多打空格。
# 3. sort() 是就地排序、返回 None。别写 idx = idx.sort()（会变成 None）。
