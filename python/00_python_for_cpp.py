# 6. 函数：不用写返回类型，能一次返回多个值
# ============================================================

def add(a, b):
    """两个数相加（这就是 docstring，相当于函数注释）"""
    return a + b

# 一次返回多个值 —— 本质是打包成一个 tuple
def divmod_self(a, b):
    return a // b, a % b          # C++ 要 struct 或 pair，Python 直接逗号

q, r = divmod_self(7, 2)          # 自动拆包
print(f"7/2 商 {q} 余 {r}")

# 默认参数
def greet(name, prefix="同学"):
    print(f"{prefix}{name}")

greet("孟庆")                      # 同学孟庆
greet("孟庆", prefix="学长")       # 也能指名道姓地传

# 全局变量：函数里【读】没问题，要【改】必须声明 global
counter = 0
def bump():
    global counter                # 少了这行就是"局部变量未赋值"报错
    counter += 1
bump()
print("counter =", counter)


# ============================================================
# 7. C++ 有、Python 没有的东西（别去找了，真没有）
# ============================================================
# - 类型声明：int / double / char 一律不写
# - 指针 * 、引用 & 、取地址 & ：Python 里"变量名的绑定"就是引用语义
# - 大括号 {} 分块：靠缩进 + 冒号
# - switch：用 if / elif / else，或者字典映射
# - do-while：没有，用 while True + break
# - 头文件 / #include：用 import
# - 三元运算符 x ? a : b  ->  写成  a if x else b
score = 75
level = "及格" if score >= 60 else "挂了"
print(level)


