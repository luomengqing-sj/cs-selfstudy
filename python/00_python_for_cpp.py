# ============================================================
# 1. 输入输出：最大的第一道坎
# ============================================================

# C++：cin >> a >> b;   —— 按"空白"切，自动转类型
# Python：input() 把一整行原封不动读成【字符串】，要自己切、自己转类型

line = "4 9"                      # 假设这是一行输入
parts = line.split()              # ['4', '9']  按空白切成字符串列表
n, target = map(int, parts)       # map 把每个元素送进 int() 转类型
# 上面那句等价于 C++ 的：cin >> n >> target;

# 读一整行 n 个数字：
# rpm = list(map(int, input().split()))
# 拆开看：input() 读行 -> split() 切成字符串 -> map(int,...) 逐个转 int -> list() 收成列表
# 类比：C++ 里 for(int i=0;i<n;i++) cin >> rpm[i];

# 输出：print 会自动在参数之间加空格，末尾加换行
print("n =", n, "target =", target)     # 输出：n = 4 target = 9
# C++ 要写成：cout << "n = " << n << " target = " << target << endl;

# 不想要末尾换行：
print("不换行", end="")
print("<- 这句会紧跟在后面")

# 格式化输出：f-string（C++ 里最接近 printf）
x, y = 3, 4
print(f"{x} + {y} = {x + y}")           # 3 + 4 = 7
print(f"{3.14159:.2f}")                 # 3.14  冒号后是格式，.2f = 两位小数


# ============================================================
# 2. 变量与类型：不声明，但不是没有类型
# ============================================================

a = 10            # 不用写 int a = 10
a = "hello"       # 甚至能改成别的类型（C++ 绝对不行）
# 但值本身有类型：type(10) 是 int，type("hi") 是 str

# ★ int 是【无限精度】的，不会溢出！
big = 2 ** 200      # 2^200，C++ 里早就爆了
print("2^200 的位数：", len(str(big)))

# 布尔值首字母大写（C++ 是小写 true/false）
flag = True
print(type(flag))   # <class 'bool'>


# ============================================================
# 3. 运算符：三个最容易翻车的地方
# ============================================================

# ① 除法：/ 永远得到浮点数（C++ 里 int/int 会截断成 int）
print("7 / 2   =", 7 / 2)      # 3.5     ← C++ 会给 3
print("7 // 2  =", 7 // 2)     # 3       ← 这才是 C++ 的整除
print("7 % 2   =", 7 % 2)      # 1       取模，两边一样

# ② 负数整除方向相反！这是隐藏雷
print("-7 // 2 =", -7 // 2)    # -4      Python 向【下】取整
# C++ 里 -7 / 2 == -3（向【零】取整）。移植代码时这里必炸。

# ③ 幂运算有专门运算符 **（C++ 只能 pow()）
print("2 ** 10 =", 2 ** 10)    # 1024

# 逻辑运算用英文单词，不是符号
if x > 0 and y > 0:            # C++: if (x > 0 && y > 0)
    pass
if not flag:                   # C++: if (!flag)
    pass

# 比较可以连着写（C++ 里这是错的，Python 里是语法）
if 1 <= x <= 5:                # 等价于 1 <= x and x <= 5
    print("x 在 1 到 5 之间（含端点）")


# ============================================================
# 4. 缩进就是大括号：没有 {} ，没有 i++
# ============================================================

# C++: for (int i = 0; i < 5; i++) { ... }
# Python 只有"遍历容器"这一种 for：
for i in range(5):             # range(5) = 0,1,2,3,4  注意【不含 5】
    print(i, end=" ")
print()                        # 上面这句只是换个行

# 没有 i++ / ++i 这种写法，只能：
i = 0
i += 1                         # 这就行了

# while 和 C++ 一样，但没有 do-while
while i < 3:
    i += 1

# 要同时拿下标和值 -> enumerate（C++ 里你要写 for(int i=0;...) 再 v[i]）
nums = [10, 20, 30]
for idx, val in enumerate(nums):
    print(f"nums[{idx}] = {val}")


# ============================================================
# 5. 容器：C++ STL 对照表
# ============================================================

# list  <->  vector
v = [1, 2, 3]
v.append(4)          # push_back
v.pop()              # pop_back，而且【返回】被弹掉的元素
print("len(v) =", len(v))          # 注意是 len() 函数，不是 v.size()
print("v[-1] =", v[-1])            # 负下标 = 从后往前数，C++ 没这玩意

# 切片：v[起:止)，【左闭右开】，跟 C++ 的 end() 一个脾气
print("v[1:3] =", v[1:3])          # 取下标 1、2，不含 3
print("v[:2]  =", v[:2])           # 从头到下标 1
print("v[::-1]=", v[::-1])         # 整个倒过来

# ★ 别名陷阱（你 02 踩过）：
b = v                # 这是给同一块地【起了第二个名字】，不是复制！
b.append(99)         # v 也跟着变了
print("v 被 b 连累了：", v)
c = v[:]             # 这样才是真复制（切片取全部 = 新建一份）
c.append(0)
print("v 这次没变：", v)

# dict  <->  unordered_map / map
d = {"one": 1, "two": 2}
d["three"] = 3                     # 插入/赋值
print(d.get("four", 0))            # 取不到就给默认值 0，不报错
# ★ 千万别直接 d["four"] —— 取不到会抛 KeyError，程序直接崩。
#    C++ 的 map[k] 取不到会【悄悄插入一个 0】，Python 不会惯着你。
if "one" in d:                     # 判断键是否存在（不是值！）
    print("键 one 存在，值是", d["one"])

for k, val in d.items():           # 遍历键值对
    print(k, "->", val, end=" | ")
print()

# set <-> unordered_set：自动去重，支持 in
s = {1, 2, 2, 3}
print("set 去重后：", s)

# tuple 元组：不可变的 list，能当 dict 的键（list 不行）
t = (1, 2)
# t[0] = 9   # 会报错，元组不能改

# str 字符串：也是"序列"，能用下标和切片，但【不可变】
word = "hello"
print("word[1:3] =", word[1:3])
# word[0] = "H"   # 报错！C++ 的 string 能改，Python 的 str 不能，只能新建：
word2 = "H" + word[1:]


