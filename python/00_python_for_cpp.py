# 8. 血泪易错榜（踩过一次就记住了）
# ============================================================
# 1) sort() 就地排序，【返回 None】；要新列表用 sorted()
lst = [3, 1, 2]
lst.sort()                 # 正确：lst 自己变了，别写 lst = lst.sort()
print("排序后：", lst, " sorted() 给新列表：", sorted([3, 1, 2]))
#
# 2) append() 也返回 None，同样的坑
#
# 3) [0] * 3 是 [0,0,0]，但 [[0]]*3 三行是【同一个列表】（别名陷阱）
#
# 4) range(n) 不含 n —— 少循环一次是家常便饭
#
# 5) 除法 / 得小数，整除要用 //
#
# 6) 缩进别混空格和 Tab，会报莫名其妙的错
#
# 7) == 比的是【值】，is 比的是【是不是同一块内存】
#    判断字符串/数字相等一律用 ==，别用 is
#
# 8) dict[k] 取不到就崩，先 in 或用 .get(k, 默认)
#
# 9) 列表当函数默认参数会出事：def f(a, buf=[]) —— 别这么写
