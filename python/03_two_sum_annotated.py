# ============================================================
# P0001 · 电机配对校准 —— 带讲义版
# 原文件 03_two_sum.py 保持不动，这份是「注释即讲义」的对照版
#
# 解法有个正经名字：**哈希表一次遍历**（也叫"边扫边存"）
# 它是 LeetCode 第 1 题 Two Sum 的标准解，不是这题的巧合做法
# 以后凡是"在一堆东西里找两个满足某关系"的题，先想它
# ============================================================

# --- 第 1 行：读第一行输入 ---
# input()         读走**一整行**，拿到的是字符串 "5 12"
# .split()        按空格切成列表：["5", "12"]     ← 还是字符串！
# map(int, ...)   把每个元素套上 int()：5, 12      ← 现在才是整数
# n, target =     拆包：左边两个名字，右边两个值，一一对应
n, target = map(int, input().split())
# ⚠️ 坑：split() 不写参数时，会按"任意多个空白"切（多个空格、Tab 都行），
#        所以输入里多打几个空格也不会错。
# ⚠️ 坑：左边名字的个数必须和右边值的个数一样多，否则 ValueError。
# 📌 提示：本解里 n 其实没用上（循环自己会走到列表结束）。
#        这不算错——真要用它，可以写 rpm = rpm[:n] 把多余的砍掉。

# --- 第 2 行：读第二行输入，收成列表 ---
# list(...)       把 map 这个"一次性迭代器"收成真正的列表，才能反复用
rpm = list(map(int, input().split()))
# ⚠️ 坑：不套 list() 的话，map 对象只能遍历一次，第二次就是空的。
#    C++ 对照：相当于 cin >> n >> target; 然后 for 循环 cin >> rpm[i];

# --- 第 3 行：建空字典 ---
# C++ 对照：unordered_map<int, int> seen;
# 约定（最关键的一条）：**键 = 转速值，值 = 下标**
# 为什么这么定？因为后面要"按值去查"——查东西只能按键查，不能按值查。
seen = {}

# --- 第 4 行：边扫边存 ---
# enumerate(rpm)  一次同时给出 (下标, 值)，顶掉 C++ 的 for(int i=0;i<n;i++) + rpm[i]
# i 是下标，x 是当前这个电机的转速
for i, x in enumerate(rpm):
    need = target - x          # 还差多少？我要找的搭档就是这个数

    if need in seen:           # 先查：那个搭档以前出现过吗？
        # in 判断的是**键**在不在。取之前必须判断——
        # Python 的 dict[k] 取不到会直接抛 KeyError 崩掉，
        # 不像 C++ 的 map[k] 会悄悄插一个 0 进去。这是两语言最大的行为差异。
        print(seen[need], i)   # seen[need] = 搭档的下标（先出现，一定更小），i = 我的下标
        break                  # 题目保证唯一解，找到就走，别白跑

    seen[x] = i                # 后存：没配上，把自己登记进名单，等后面的人来找我

# ============================================================
# ★ 为什么必须「先查后存」？——用 [3, 3], target=6 想一遍
#
#   正确顺序（先查后存）：
#     i=0, x=3, need=3 → 名单空的，没查到 → 登记 {3: 0}
#     i=1, x=3, need=3 → 名单里有 3（下标 0）→ 输出 0 1 ✅
#
#   错误顺序（先存后查）：
#     i=0, x=3 → 先登记 {3: 0} → 再查 need=3 → **查到自己**
#     输出 0 0 ❌（同一个电机用了两次）
#
#   口诀：**先问"来了没"，再坐下等。**
# ============================================================

# ============================================================
# ★ 这个解法的一个真实性质（自己踩过一次才知道）
#
# 它返回的是「**右端点最靠前**」的那组解——第二个数一出现就配对走人，
# 根本不给"左端点更靠前"的那一对机会。
#
# 例：[3,4,6,7,8], target=10 有两组解：3+7 → (0,3) 和 4+6 → (1,2)
#     本解会输出 1 2，因为 6（i=2）比 7（i=3）先出现。
#
# 题目保证唯一解时完全无所谓。但**不要以为它天然返回下标最小的那组**。
# ============================================================

# ============================================================
# 复杂度（洛谷为什么会卡你）
#   暴力两两配对：O(n²)。n = 10⁴ 时要配 10⁸ 次 → 超时 TLE
#   本解：只扫一趟，每次查表 O(1) → **O(n)**
#   代价：多用了一个字典，空间 O(n)。这就是"拿空间换时间"。
# ============================================================
